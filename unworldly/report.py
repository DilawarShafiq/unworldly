"""Report generation for Unworldly.

Generates terminal and markdown security reports from recorded sessions,
including integrity verification and ISO 42001 audit-evidence sections.
"""

from __future__ import annotations

from datetime import datetime

from .display import banner, verify_display
from .integrity import verify_session
from .session import load_session
from .types import Session, WatchEvent


def capture_coverage(capture_source: str | None) -> tuple[str, str]:
    """Map a session's capture source to a (label, honest coverage note).

    A sealed log is only as trustworthy as what it could see; every report
    states its coverage scope so an incomplete log is never mistaken for a
    complete one (FR-007 / capture-honesty contract).
    """
    if capture_source is None:
        return (
            "Filesystem + shell (watch)",
            "File changes and shell commands on this machine. Does NOT include the agent's "
            "prompts/reasoning, in-process SDK tool calls, or actions taken off this machine.",
        )
    mapping: dict[str, tuple[str, str]] = {
        "sdk-trace": (
            "SDK tool-call trace",
            "In-process tool calls the agent made (decision trail). Does NOT include file/shell "
            "activity unless a watch session also ran.",
        ),
        "mcp": (
            "MCP tool-call capture",
            "Tool calls routed through MCP. Does NOT include file/shell activity or non-MCP tools.",
        ),
        "otel": (
            "OpenTelemetry GenAI",
            "Tool/model spans emitted by the agent. Coverage depends on what the agent instrumented.",
        ),
    }
    if capture_source in mapping:
        return mapping[capture_source]
    return (capture_source, f"Captured via '{capture_source}'. Coverage scope not further specified.")


def _group_by_risk(events: list[WatchEvent]) -> dict[str, list[WatchEvent]]:
    """Group events by their risk level."""
    result: dict[str, list[WatchEvent]] = {}
    for event in events:
        risk_val = event.risk.value if hasattr(event.risk, "value") else event.risk
        if risk_val not in result:
            result[risk_val] = []
        result[risk_val].append(event)
    return result


def _format_time(iso_string: str) -> str:
    """Format an ISO timestamp as HH:MM:SS."""
    dt = datetime.fromisoformat(iso_string.replace("Z", "+00:00"))
    return dt.strftime("%H:%M:%S")


def _generate_markdown(session: Session) -> str:
    """Generate a markdown security report from a session."""
    summary = session.summary
    events = session.events
    start_date = datetime.fromisoformat(session.start_time.replace("Z", "+00:00")).strftime("%c")
    end_date = (
        datetime.fromisoformat(session.end_time.replace("Z", "+00:00")).strftime("%c") if session.end_time else "N/A"
    )

    danger_events = [e for e in events if e.risk.value == "danger"]
    caution_events = [e for e in events if e.risk.value == "caution"]

    # Verify integrity for compliance section
    integrity = verify_session(session)

    agent_row = ""
    if session.agent:
        agent_row = f"| Agent | {session.agent.name} ({session.agent.detected_via}) |\n"
        if session.agent.model:
            agent_row += f"| Model | {session.agent.model} |\n"
        if session.agent.version:
            agent_row += f"| Agent Version | {session.agent.version} |\n"

    capture_label, capture_note = capture_coverage(session.capture_source)
    from .custody import describe_custody

    custody_rows = "".join(f"| {label} | {value} |\n" for label, value in describe_custody(session.custody))
    agent_row += custody_rows

    integrity_issues = ""
    if integrity.errors:
        issues = "\n".join(f"- {e}" for e in integrity.errors)
        integrity_issues = f"\n**Issues:**\n{issues}\n"
    trail = "Signed, tamper-resistant" if integrity.signed else "Tamper-evident (unsigned)"

    md = f"""# Unworldly Security Report

> Generated by [Unworldly](https://github.com/DilawarShafiq/unworldly) — The Flight Recorder for AI Agents
> {trail} audit trail (supports ISO 42001 / SOC 2 evidence)

## Session Overview

| Field | Value |
|-------|-------|
| Session ID | `{session.id}` |
| Version | `{session.version}` |
| Directory | `{session.directory}` |
| Started | {start_date} |
| Ended | {end_date} |
| Total Events | {summary.total_events} |
| Risk Score | **{summary.risk_score}/10** |
| Capture | {capture_label} |
{agent_row}
## Capture Coverage

> **{capture_label}.** {capture_note}

## Integrity Verification

| Check | Status |
|-------|--------|
| Hash Chain | {integrity.valid_events}/{integrity.total_events} events verified |
| Session Seal | {"Valid" if integrity.session_hash_valid else "Invalid or missing"} |
| Overall | {"**PASSED** — No tampering detected" if integrity.valid else "**FAILED** — Possible tampering"} |
| Result | {integrity.status.replace("_", " ")} |
{integrity_issues}
## Risk Breakdown

| Level | Count |
|-------|-------|
| Safe | {summary.safe} |
| Caution | {summary.caution} |
| Danger | {summary.danger} |

"""

    if session.usage:
        u = session.usage
        md += "## Token Usage\n\n"
        md += "| Metric | Tokens |\n|--------|--------|\n"
        md += f"| Input | {u.get('inputTokens', 0):,} |\n"
        md += f"| Output | {u.get('outputTokens', 0):,} |\n"
        md += f"| **Total** | **{u.get('totalTokens', 0):,}** |\n\n"
        md += "> Cost = total tokens × your model's per-token rate.\n\n"

    if danger_events:
        md += "## Dangerous Actions\n\n"
        md += "| Time | Action | Target | Reason |\n"
        md += "|------|--------|--------|--------|\n"
        for e in danger_events:
            time_str = _format_time(e.timestamp)
            action = "COMMAND" if e.type.value == "command" else e.type.value.upper()
            md += f"| {time_str} | {action} | `{e.path}` | {e.reason or '-'} |\n"
        md += "\n"

    if caution_events:
        md += "## Caution Actions\n\n"
        md += "| Time | Action | Target | Reason |\n"
        md += "|------|--------|--------|--------|\n"
        for e in caution_events:
            time_str = _format_time(e.timestamp)
            action = "COMMAND" if e.type.value == "command" else e.type.value.upper()
            md += f"| {time_str} | {action} | `{e.path}` | {e.reason or '-'} |\n"
        md += "\n"

    # Commands Executed section
    command_events = [e for e in events if e.type.value == "command"]
    if command_events:
        md += "## Commands Executed\n\n"
        md += "| # | Time | Command | Run by | Risk | Reason |\n"
        md += "|---|------|---------|--------|------|--------|\n"
        for i, e in enumerate(command_events):
            time_str = _format_time(e.timestamp)
            if e.risk.value == "danger":
                risk_str = "🚨 DANGER"
            elif e.risk.value == "caution":
                risk_str = "⚠️ Caution"
            else:
                risk_str = "✅ Safe"
            actor = e.command.actor if e.command and e.command.actor else "unknown"
            md += f"| {i + 1} | {time_str} | `{e.path}` | {actor} | {risk_str} | {e.reason or '-'} |\n"
        md += "\n"
        others = sum(1 for e in command_events if e.command and e.command.actor == "other")
        if others:
            md += (
                f"> {others} command(s) were run by something other than the agent (e.g. you, in another terminal).\n\n"
            )

    from .flags import find_flags

    found = find_flags(session)
    if found:
        md += "## Behaviour Flags\n\n"
        md += "> Computed from the signed record: chains of events, installs, git operations, loops.\n\n"
        md += "| Level | Kind | Finding | Events |\n|-------|------|---------|--------|\n"
        for f in found:
            level = "🚨 DANGER" if f.level.value == "danger" else "⚠️ Caution"
            where = ", ".join(f"#{n}" for n in f.events)
            md += f"| {level} | {f.kind} | {f.message.replace('|', '/')} | {where} |\n"
        md += "\n"

    used = [(n, e) for n, e in enumerate(events, start=1) if e.credentials]
    indexed = (session.credential_index or {}).get("credentials", [])
    if indexed or used:
        md += "## Credential Lineage\n\n"
        md += f"> {len(indexed)} credential(s) indexed at session start (fingerprints only, never values).\n\n"
        if used:
            md += "| Event | Credential | Source | Action |\n|-------|------------|--------|--------|\n"
            for n, e in used:
                for ref in e.credentials or []:
                    source, _, name = ref.rpartition("#")
                    md += f"| #{n} | `{name}` | `{source}` | `{e.path[:80]}` |\n"
            md += "\n"
        else:
            md += "No indexed credential was used in this session.\n\n"

    changed = [e for e in events if e.diff][:20]
    if changed:
        md += "## File Changes\n\n"
        md += "> Diffs are size-capped and secrets are redacted. Credential files are never diffed.\n\n"
        for e in changed:
            md += f"### `{e.path}` ({e.type.value}, {e.risk.value})\n\n```diff\n{e.diff}```\n\n"

    md += "## Full Event Timeline\n\n"
    md += "| # | Time | Action | Target | Risk |\n"
    md += "|---|------|--------|--------|------|\n"
    for i, e in enumerate(events):
        time_str = _format_time(e.timestamp)
        action = "COMMAND" if e.type.value == "command" else e.type.value.upper()
        if e.risk.value == "danger":
            risk_str = "🚨 DANGER"
        elif e.risk.value == "caution":
            risk_str = "⚠️ Caution"
        else:
            risk_str = "✅ Safe"
        md += f"| {i + 1} | {time_str} | {action} | `{e.path}` | {risk_str} |\n"

    md += f"\n---\n*Report generated by Unworldly v{session.version}*\n"

    return md


def report(
    session_path: str,
    output: str | None = None,
    format: str = "terminal",
    include_owasp: bool = False,
) -> None:
    """Generate a security report from a recorded session.

    Args:
        session_path: Path to the session file or session ID.
        output: Output file path (for markdown format).
        format: Output format -- "terminal" or "md"/"markdown".
    """
    session = load_session(session_path)

    green = "\033[32m"
    gray = "\033[90m"
    white_bold = "\033[1;37m"
    white = "\033[37m"
    cyan = "\033[36m"
    yellow = "\033[33m"
    yellow_bold = "\033[1;33m"
    red = "\033[31m"
    red_bold = "\033[1;31m"
    reset = "\033[0m"

    if format in ("md", "markdown"):
        markdown = _generate_markdown(session)
        if include_owasp:
            from .owasp import map_session, owasp_markdown_section

            findings = map_session(session)
            markdown += "\n" + owasp_markdown_section(findings)
        output_path = output or f"unworldly-report-{session.id}.md"
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(markdown)
        print(banner())
        print(f"{green}  Report saved: {output_path}{reset}")
        print("")
        return

    # Terminal format
    print(banner())
    print(f"{white_bold}  Security Report{reset}")
    print("")

    summary = session.summary
    if summary.risk_score >= 7:
        score_color = red_bold
    elif summary.risk_score >= 4:
        score_color = yellow_bold
    else:
        score_color = "\033[1;32m"

    print(f"  Session:   {white}{session.id}{reset}")
    print(f"  Directory: {gray}{session.directory}{reset}")
    start_str = datetime.fromisoformat(session.start_time.replace("Z", "+00:00")).strftime("%c")
    print(f"  Recorded:  {gray}{start_str}{reset}")
    if session.agent:
        print(f"  Agent:     {cyan}{session.agent.name}{reset} {gray}({session.agent.detected_via}){reset}")
    from .custody import describe_custody

    for label, value in describe_custody(session.custody):
        print(f"  {label + ':':<11}{gray}{value}{reset}")
    capture_label, capture_note = capture_coverage(session.capture_source)
    print(f"  Capture:   {white}{capture_label}{reset}")
    print(f"  {gray}Coverage:  {capture_note}{reset}")
    if session.usage:
        total = session.usage.get("totalTokens", 0)
        print(
            f"  Tokens:    {white}{total:,}{reset} {gray}(in {session.usage.get('inputTokens', 0):,}"
            f" / out {session.usage.get('outputTokens', 0):,}){reset}"
        )
    print("")

    # Integrity verification
    integrity = verify_session(session)
    print(verify_display(integrity))
    print(f"  Risk Score: {score_color}{summary.risk_score}/10{reset}")
    print("")
    print(
        f"  {green}●{reset} Safe: {summary.safe}  "
        f"{yellow}●{reset} Caution: {summary.caution}  "
        f"{red}●{reset} Danger: {summary.danger}"
    )
    print("")

    danger_events = [e for e in session.events if e.risk.value == "danger"]
    caution_events = [e for e in session.events if e.risk.value == "caution"]

    if danger_events:
        print(f"{red_bold}  Dangerous Actions:{reset}")
        for e in danger_events:
            time_str = _format_time(e.timestamp)
            action = "$> CMD" if e.type.value == "command" else e.type.value.upper()
            print(f"{red}    {time_str}  {action}  {e.path}  — {e.reason}{reset}")
        print("")

    if caution_events:
        print(f"{yellow_bold}  Caution Actions:{reset}")
        for e in caution_events:
            time_str = _format_time(e.timestamp)
            action = "$> CMD" if e.type.value == "command" else e.type.value.upper()
            print(f"{yellow}    {time_str}  {action}  {e.path}  — {e.reason}{reset}")
        print("")

    from .display import format_finding
    from .flags import find_flags

    found = find_flags(session)
    if found:
        print(f"\033[1;35m  Behaviour Flags:{reset}")
        for finding in found:
            print(format_finding(finding))
        print("")

    if summary.risk_score >= 7:
        print(f"{red_bold}  ⚠ HIGH RISK SESSION — Review dangerous actions above{reset}")
    elif summary.risk_score >= 4:
        print(f"{yellow}  Some concerning activity detected — review caution items{reset}")
    else:
        print(f"{green}  Session looks clean — no major concerns{reset}")
    print("")

    if include_owasp:
        from .owasp import map_session, owasp_terminal_report

        findings = map_session(session)
        print(owasp_terminal_report(findings))

    # Suggest markdown export
    print(f"{gray}  Export full report: unworldly report {session_path} --format md{reset}")
    print("")
